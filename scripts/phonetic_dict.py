def normalize_phonetics(text):
    """テキストを自然なアナウンサー調日本語読みに正規化"""
    if not text:
        return ""

    # 重複する語尾バグの修正
    text = re.sub(r'ですです', 'です', text)
    text = re.sub(r'ますます', 'ます', text)
    text = re.sub(r'でしたでした', 'でした', text)
    text = re.sub(r'！！+', '！', text)
    text = re.sub(r'？？+', '？', text)
    text = re.sub(r'[、]{2,}', '、', text)
    text = re.sub(r'[。]{2,}', '。', text)

    # 最重要：何mm / 何ミリメートルの読み間違い（「なに」ではなく「なん」）の強制置換
    text = re.sub(r'何\s*(?:mm|MM|ミリメートル|ミリ|ﾐﾘ)', 'なんミリ', text)
    text = re.sub(r'何\s*(?:cm|CM|センチメートル|センチ|ｾﾝﾁ)', 'なんセンチ', text)
    text = re.sub(r'何\s*(?:m2|㎡|平米|平方メートル)', 'なんへいべい', text)
    text = re.sub(r'何\s*(?:m|M|メートル|ﾒｰﾄﾙ)\b', 'なんメートル', text)
    text = re.sub(r'何\s*(?:寸)', 'なんずん', text)
    text = re.sub(r'何\s*(?:尺)', 'なんじゃく', text)
    text = re.sub(r'何\s*(?:間)', 'なんげん', text)
    text = re.sub(r'何\s*(?:坪)', 'なんつぼ', text)
    text = re.sub(r'何\s*(?:帖|畳)', 'なんじょう', text)
    text = re.sub(r'何\s*(?:段)', 'なんだん', text)
    text = re.sub(r'何\s*(?:階)', 'なんかい', text)

    # 社名連呼の完全削除（純粋な解説・寸法ノウハウに尺を100%割り振る）
    text = re.sub(r'埼玉の高気密高断熱なら住ま居るへ！?', '', text)
    text = re.sub(r'埼玉の住ま居る[。！]?', '', text)
    text = re.sub(r'住ま居るの家づくり[。！]?', '', text)
    text = re.sub(r'住ま居るにお任せ[。！]?', '', text)
    text = re.sub(r'住ま居る[。！]?', '', text)
    text = re.sub(r'【住ま居る】', '', text)
    text = re.sub(r'株式会社住ま居る', '', text)

    # 専門用語・略称・記号の発音置換
    for pattern, replacement in PHONETIC_REPLACEMENTS:
        text = re.sub(pattern, replacement, text)

    # カンマ入り数字（1,000 -> 1000）
    text = re.sub(r'(\d+),(\d+)', r'\1\2', text)

    # 末尾の整理
    text = text.strip()
    if text and not text.endswith(('。', '！', '？', 'です', 'ます', '正解', '基準')):
        text += '。'

    return text
