    /**
     * 現在選択中のモード・ツール・サブツールに対応するマニュアル項目IDを返す
     */
    function resolveManualIdForCurrentTool(stateObj) {
        if (!stateObj) return 'ch3_wall_draw';
        const tool = stateObj.activeTool || 'wall';
        const subWall = stateObj.subWallType || 'wall';
        const subOp = stateObj.subOpeningFit || stateObj.subDoorFit || 'hikichigai';
        const subRm = stateObj.subRoomType || 'LDK';
        const subFx = stateObj.subFixtureCategory || 'KITCHEN';

        // 複合キー優先検索
        if (tool === 'wall' && TOOL_MANUAL_MAP[`wall:${subWall}`]) {
            return TOOL_MANUAL_MAP[`wall:${subWall}`];
        }
        if (tool === 'opening' && TOOL_MANUAL_MAP[`opening:${subOp}`]) {
            return TOOL_MANUAL_MAP[`opening:${subOp}`];
        }
        if (tool === 'room' && TOOL_MANUAL_MAP[`room:${subRm}`]) {
            return TOOL_MANUAL_MAP[`room:${subRm}`];
        }
        if (tool === 'fixture' && TOOL_MANUAL_MAP[`fixture:${subFx}`]) {
            return TOOL_MANUAL_MAP[`fixture:${subFx}`];
        }
        if (TOOL_MANUAL_MAP[tool]) {
            return TOOL_MANUAL_MAP[tool];
        }
        if (stateObj.paletteMode === 'memo') return 'ch5_memo_overview';
        if (stateObj.paletteMode === 'photo') return 'ch5_camera_sketch';
        return 'ch3_wall_draw';
    }

